#!/usr/bin/env python3
"""Generate src/segmenter_tables.rs from go-text/typesetting v0.3.4.

Evaluates go-text's generated multi-stage lookups (internal/unicodedata
grapheme_break.go, indic_conjunct_break.go, emojis.go; Unicode 17.0.0) for
every scalar value and emits sorted (first, last, value) ranges, so Rust
reads exactly the pinned Go property data.

usage: generate_segmenter_tables.py <go-text module dir> > src/segmenter_tables.rs
"""
import re
import sys
from pathlib import Path

root = Path(sys.argv[1]) / "internal/unicodedata"


def load(file, prefix):
    src = (root / file).read_text()
    array = re.search(prefix + r"Uint8 = \[\d+\]uint8\{([^}]*)\}", src).group(1)
    data = [int(v) for v in array.replace("\n", " ").split(",") if v.strip()]
    body = re.search(r"func " + prefix + r"Lookup\(u rune\) uint8 \{\s*if 0 <= u && u < (\d+) \{\s*return (.*)\n", src)
    limit, expr = int(body.group(1)), body.group(2)
    bits = {int(n) for n in re.findall(prefix + r"Bits(\d)", src)}
    expr = re.sub(prefix + r"Bits(\d)\(" + prefix + r"Uint8\[(\d*):\],", lambda m: f"bits({m.group(1)}, {m.group(2) or 0},", expr)
    expr = re.sub(prefix + r"Uint8\[", "A[", expr)
    expr = expr.replace("int(", "(")
    expr = re.sub(r"<<(\d+)", lambda m: f"*{1 << int(m.group(1))}", expr)
    expr = re.sub(r">>(\d+)", lambda m: f"//{1 << int(m.group(1))}", expr)

    def bits_fn(width, base, i):
        per = 8 // width
        return (data[base + i // per] >> ((i % per) * width)) & ((1 << width) - 1)

    code = compile(expr, prefix, "eval")
    values = []
    for u in range(0x110000):
        values.append(eval(code, {"A": data, "bits": bits_fn, "u": u}) if u < limit else 0)
    del bits
    return values


def ranges(values):
    out = []
    start = 0
    for u in range(1, 0x110001):
        if u == 0x110000 or values[u] != values[start]:
            if values[start]:
                out.append((start, u - 1, values[start]))
            start = u
    return out


def emit(name, rows):
    print(f"pub(crate) static {name}: &[(u32, u32, u8)] = &[")
    for first, last, value in rows:
        print(f"    (0x{first:x}, 0x{last:x}, {value}),")
    print("];")


print("// SPDX-License-Identifier: Unlicense OR BSD-3-Clause")
print("// Generated by scripts/generate_segmenter_tables.py from go-text/typesetting")
print("// v0.3.4 internal/unicodedata (Unicode 17.0.0). DO NOT EDIT.")
print("// Values are go-text's raw lookup indices (property bit = 1 << (value - 1)).")
print()
emit("GRAPHEME_BREAK", ranges(load("grapheme_break.go", "gb")))
emit("INDIC_CONJUNCT_BREAK", ranges(load("indic_conjunct_break.go", "indicCB")))
emit("EXTENDED_PICTOGRAPHIC", ranges(load("emojis.go", "emoji")))
