#!/usr/bin/env python3
"""Translate pinned default command recognition, with original-oracle audit.

This table describes recognition only. It never supplies rendered output and
does not claim that recognized commands have native implementations.
"""
import argparse
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path


def candidates(source: Path) -> list[str]:
    names = set()
    for path in source.glob("*.go"):
        if path.name.endswith("_test.go"):
            continue
        text = path.read_text()
        names.update(re.findall(r'"([A-Za-z]+)"', text))
        names.update(re.findall(r'Name:\s*"\\\\([A-Za-z]+)"', text))
    return sorted(names)


def recognized(row: dict) -> bool:
    # Invoke the actual original default command dispatch through D2. Missing
    # arguments and other diagnostics still establish that a name is recognized.
    errors = [node.attrib["data-mjx-error"]
              for node in ET.fromstring(row["svg"]).iter()
              if "data-mjx-error" in node.attrib]
    return errors != ["Undefined control sequence \\" + row["command"]]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("oracle", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--contracts", type=Path)
    args = parser.parse_args()
    rows = json.loads(args.oracle.read_text())
    assert [row["command"] for row in rows] == candidates(args.source)
    assert all(row["expression"] == "\\" + row["command"] for row in rows)
    names = [row["command"] for row in rows if recognized(row)]
    args.output.write_text(
        "// Copyright 2009-2022 The MathJax Consortium\n"
        "// SPDX-License-Identifier: Apache-2.0\n"
        "// Pinned mathjax-go v0.1.0 tex command dispatch/default namespace.\n"
        "// Generated by scripts/generate-math-command-registry.py; SOURCE.md.\n"
        "// Recognition does not mean that the native handler is implemented.\n"
        "pub(super) fn recognized(name: &str) -> bool {\n"
        "    COMMANDS.binary_search(&name).is_ok()\n}\n"
        "pub(super) const COMMANDS: &[&str] = &[\n"
        + "".join("    " + json.dumps(name) + ",\n" for name in names)
        + "];\n")
    if args.contracts:
        args.contracts.write_text(json.dumps([
            {"command": row["command"], "recognized": recognized(row)}
            for row in rows], indent=2) + "\n")
    print(f"{len(names)} recognized names / {len(rows)} source candidates")


if __name__ == "__main__":
    main()
