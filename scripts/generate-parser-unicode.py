#!/usr/bin/env python3
"""Generate block-string character classification from the pinned Go oracle."""
import json
import subprocess
from references import ROOT, REFERENCE, verify_source, digest, MANIFEST
verify_source()
oracle=REFERENCE / "bin/parser-oracle"
record=json.loads(oracle.with_suffix(".provenance.json").read_text())
assert record["go_toolchain"] == MANIFEST["d2"]["go_toolchain"]
assert record["binary_sha256"]==digest(oracle)
assert record["harness_sha256"]==digest(ROOT / "tools/parser-oracle/main.go")
data=json.loads(subprocess.check_output([str(oracle),"unicode"]))
out='// SPDX-License-Identifier: MPL-2.0\n// Generated by scripts/generate-parser-unicode.py from Go 1.27.0.\n'
out+=f'// Unicode {data["version"]}.\n'
for name,ranges in sorted(data["tables"].items()):
 table=name.upper()
 out+=f'pub fn is_{name}(r: char) -> bool {{ let r=r as u32;let i={table}.partition_point(|range|range.1<r);{table}.get(i).is_some_and(|range|range.0<=r) }}\n'
 out+=f'const {table}: &[(u32,u32)] = &[\n'+''.join(f'    (0x{a:x},0x{b:x}),\n' for a,b in ranges)+'];\n'
out+='pub fn to_lower(r: char) -> char { let r=r as u32; let i=LOWER.partition_point(|pair|pair.0<r); char::from_u32(LOWER.get(i).filter(|pair|pair.0==r).map_or(r,|pair|pair.1)).unwrap() }\n'
out+='const LOWER: &[(u32,u32)] = &[\n'+''.join(f'    (0x{a:x},0x{b:x}),\n' for a,b in data['lower'])+'];\n'
path=ROOT / "crates/d2-rs-language/src/parser/unicode.rs"
path.write_text(out)
subprocess.run(["rustfmt","--edition","2024",str(path)],check=True)
(ROOT / "docs/parser-unicode-reference.json").write_text(json.dumps({"go_toolchain":record["go_toolchain"],"unicode_version":data["version"],"ranges":{k:len(v) for k,v in data["tables"].items()},"simple_lowercase_mappings":len(data["lower"]),"classification":"Go letter/digit union, digits, printability and simple lowercase across all Unicode code points","oracle_sha256":digest(oracle),"rust_table_sha256":digest(path)},indent=2)+"\n")
print("Generated pinned Unicode tables")
